// Build the Remotion timeline from the recording marks and the narration lengths.
// Writes ~/video-studio/src/stipend-timeline.ts
import fs from "node:fs";
import { execSync } from "node:child_process";
import os from "node:os";

const REC = "docs/video/rec", VO = "docs/video/vo";
const marks = (clip) => Object.fromEntries(JSON.parse(fs.readFileSync(`${REC}/${clip}.marks.json`, "utf8")).map((m) => [m.label, m.t]));
const dur = (file) => Number(execSync(`ffprobe -v error -show_entries format=duration -of csv=p=0 "${file}"`).toString().trim());

// Each segment: narration file, label, and anchored spans [clip, markLabel, preOffset, postOffset].
const PLAN = [
  { id: "s1", label: "The problem isn't the agent", vo: "s1_problem.wav", spans: [["dashboard", "loaded", 0.3, 9.6]] },
  { id: "s2", label: "So I built Stipend", vo: "s2_built.wav", spans: [["dashboard", "stats", 3.0, 13.3]] },
  { id: "s3", label: "Moment 1 · The owner signs", vo: "s3_owner.wav", spans: [["owner_signs", "owner page", 0.3, 4.2], ["owner_signs", "typed goal", -2.0, 1.6], ["owner_signs", "owner ask shown", -0.3, 7.5]] },
  { id: "s4", label: "Moment 2 · Pay per request", vo: "s4_pay.wav", spans: [["pay_per_request", "task page", 0.4, 13.8]] },
  { id: "s5", label: "Moment 3 · The planted page", vo: "s5_attack.wav", spans: [["attack_drill", "drill on", -0.8, 2.2], ["attack_drill", "planted line", -0.4, 2.4], ["attack_drill", "refused line", -0.2, 3.4], ["attack_drill", "asked line", 0.1, 1.9], ["attack_drill", "owner ask with flags", 0.0, 2.6], ["attack_drill", "declined", -1.5, 1.9], ["attack_drill", "task declined", -0.2, 2.0]] },
  { id: "s6", label: "Moment 4 · Hand back the change", vo: "s6_handback.wav", spans: [["hand_back", "task page", 0.2, 3.7], ["hand_back", "verify green", 0.1, 3.1], ["hand_back", "tamper", -0.3, 3.3]] },
  { id: "s7", label: "Every number, computed", vo: "s7_proof.wav", spans: [["readme", "proof", 0, 10.1]] },
  { id: "s8", label: "Shipped, row by row", vo: "s8_honest.wav", spans: [["readme", "fromsolana", 0, 6.5]] },
];

const out = [];
for (const seg of PLAN) {
  const n = dur(`${VO}/${seg.vo}`);
  const target = n + 0.5;
  let subs = seg.spans.map(([clip, label, pre, post]) => {
    const m = marks(clip); const len = dur(`${REC}/${clip}.mp4`);
    if (m[label] === undefined) throw new Error(`no mark ${label} in ${clip}`);
    const from = Math.max(0, m[label] + pre), to = Math.min(len, m[label] + post);
    return { src: `${clip}.mp4`, from: +from.toFixed(2), to: +to.toFixed(2), len };
  });
  let total = subs.reduce((a, s) => a + (s.to - s.from), 0);
  let rate = 1;
  if (total > target) { // trim each span's tail proportionally
    const k = target / total;
    subs = subs.map((s) => ({ ...s, to: +(s.from + (s.to - s.from) * k).toFixed(2) }));
  } else if (total < target) { // extend the last span if the clip allows, else slow it down
    const last = subs[subs.length - 1];
    const room = last.len - last.to;
    const need = target - total;
    if (room >= need) last.to = +(last.to + need).toFixed(2);
    else { last.to = +last.len.toFixed(2); rate = +(((total + room)) / target).toFixed(3); }
  }
  total = subs.reduce((a, s) => a + (s.to - s.from), 0) / rate;
  out.push({ id: seg.id, label: seg.label, vo: seg.vo, subs: subs.map(({ len, ...s }) => ({ ...s, ...(rate !== 1 ? { rate } : {}) })) });
  console.log(seg.id.padEnd(3), `vo ${n.toFixed(1)}s`, `video ${total.toFixed(1)}s`, rate !== 1 ? `rate ${rate}` : "", subs.map((s) => `${s.src.replace(".mp4", "")}[${s.from}-${s.to}]`).join(" "));
}
const ts = `// Generated by scripts/timeline.mjs in the stipend repo. Do not edit by hand.\nexport type Sub = { src: string; from: number; to: number; rate?: number };\nexport type Seg = { id: string; label: string; vo: string; subs: Sub[] };\nexport const SEGMENTS: Seg[] = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(`${os.homedir()}/video-studio/src/stipend-timeline.ts`, ts);
const body = out.reduce((a, s) => a + s.subs.reduce((b, x) => b + (x.to - x.from) / (x.rate ?? 1), 0), 0);
console.log(`body ${body.toFixed(1)}s + opener 10 + closer 8 = ${(body + 18).toFixed(1)}s`);
